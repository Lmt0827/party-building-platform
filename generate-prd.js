function h1(text) {
  return new Paragraph({ text, heading: HeadingLevel.HEADING_1, spacing: { before: 400, after: 200 } });
}

function h2(text) {
  return new Paragraph({ text, heading: HeadingLevel.HEADING_2, spacing: { before: 300, after: 150 } });
}

function h3(text) {
  return new Paragraph({ text, heading: HeadingLevel.HEADING_3, spacing: { before: 200, after: 100 } });
}

function p(text, options = {}) {
  return new Paragraph({
    children: [new TextRun({ text, ...options })],
    spacing: { after: 120 }
  });
}

function cell(text, opts = {}) {
  return new TableCell({
    children: [new Paragraph({ children: [new TextRun({ text, ...opts })] })],
    verticalAlign: docx.VerticalAlign.CENTER
  });
}

function createTable(headers, rows) {
  const tableRows = [
    new TableRow({
      children: headers.map(h => cell(h, { bold: true })),
      tableHeader: true
    }),
    ...rows.map(row => new TableRow({ children: row.map(c => cell(String(c))) }))
  ];
  return new Table({
    rows: tableRows,
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 1, color: '000000' },
      bottom: { style: BorderStyle.SINGLE, size: 1, color: '000000' },
      left: { style: BorderStyle.SINGLE, size: 1, color: '000000' },
      right: { style: BorderStyle.SINGLE, size: 1, color: '000000' },
      insideHorizontal: { style: BorderStyle.SINGLE, size: 1, color: '000000' },
      insideVertical: { style: BorderStyle.SINGLE, size: 1, color: '000000' }
    }
  });
}

function moduleBlock(title, desc, fields, preData, postData, rules = '') {
  const block = [];
  block.push(h3(title));
  block.push(p(`功能说明：${desc}`));
  if (rules) {
    block.push(p(`业务规则：${rules}`));
  }
  block.push(p('核心字段：'));
  block.push(createTable(['字段名', '字段类型', '是否必填', '说明'], fields));
  block.push(p('前置数据：'));
  block.push(createTable(['数据项', '来源', '说明'], preData));
  block.push(p('后置数据/输出：'));
  block.push(createTable(['数据项', '去向', '说明'], postData));
  return block;
}

